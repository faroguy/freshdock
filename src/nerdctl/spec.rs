    /// `["--flag", "value", …]` pairs as `"--flag value"` strings, for
    /// order-independent membership checks.
    fn pairs(args: &[String]) -> Vec<String> {
        let mut out = Vec::new();
        let mut i = 0;
        while i < args.len() {
            if args[i].starts_with("--") && i + 1 < args.len() && !args[i + 1].starts_with("--") {
                out.push(format!("{} {}", args[i], args[i + 1]));
                i += 2;
            } else {
                out.push(args[i].clone());
                i += 1;
            }
        }
        out
    }

